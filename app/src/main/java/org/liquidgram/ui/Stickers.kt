/**
 * "Claw'd Stickers": our own animated pack, shipped in the APK (generated by tools/clawd_stickers.py) and
 * unpacked into app storage on first start, so it's installed the moment the client is.
 */
object ClawdPack {
    private const val DIR = "stickers/clawd"
    var set: StickerSet? = null
        private set

    fun install(context: Context) {
        val dir = File(context.filesDir, DIR).apply { mkdirs() }
        val index = context.assets.open("$DIR/index.txt").bufferedReader().readLines().filter { it.isNotBlank() }
        set = StickerSet(-1, "Claw'd Stickers", index.map { line ->
            val (name, emoji) = line.split(" ", limit = 2)
            val file = File(dir, name)
            // Re-copied when the APK carries a different version of the file.
            val asset = context.assets.open("$DIR/$name").use { it.readBytes() }
            if (!file.exists() || file.length() != asset.size.toLong()) file.writeBytes(asset)
            Sticker(0, file.absolutePath, emoji, StickerKind.Lottie)
        })
    }
}

/** Draws a sticker: Lottie (.tgs) animates, WebP is a picture, anything else (WebM, still loading) shows its emoji. */
@Composable
fun StickerView(path: String?, kind: StickerKind, emoji: String, size: Dp, modifier: Modifier = Modifier) {
    Box(modifier.size(size).themeTint(), contentAlignment = Alignment.Center) {
        when {
            path != null && kind == StickerKind.Lottie -> LottieSticker(path)
            path != null && kind == StickerKind.Static -> rememberPhoto(path)?.let { Image(it, null, Modifier.fillMaxSize(), contentScale = ContentScale.Fit) }
            else -> T(emoji, (size.value * 0.6f).sp)
        }
    }
}

@Composable
private fun LottieSticker(path: String) {
    val json by produceState<String?>(null, path) {
        value = withContext(Dispatchers.IO) {
            runCatching {
                val bytes = File(path).readBytes()
                // .tgs is gzip; a plain .json works too.
                if (bytes.size > 2 && bytes[0] == 0x1f.toByte() && bytes[1] == 0x8b.toByte()) GZIPInputStream(bytes.inputStream()).readBytes().decodeToString()
                else bytes.decodeToString()
            }.getOrNull()
        }
    }
    val text = json ?: return
    val composition by rememberLottieComposition(LottieCompositionSpec.JsonString(text), cacheKey = path)
    LottieAnimation(composition, Modifier.fillMaxSize(), iterations = if (Look.powerStickers) 1 else LottieConstants.IterateForever)
}

