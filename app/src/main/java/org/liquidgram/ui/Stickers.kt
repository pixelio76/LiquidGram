/**
 * Emoji & sticker panel under the input bar: a frosted glass sheet. Stickers follow Telegram iOS: a row of pack
 * icons, a "Search for stickers" field, then each pack under its uppercase title, five per row.
 * Our Claw'd pack comes first, then the account's installed packs. Emoji / Stickers switch at the bottom.
 */
@Composable
fun EmojiPanel(repo: TelegramRepository, backdrop: Backdrop, onEmoji: (String) -> Unit, onSticker: (Sticker) -> Unit) {
    var tab by rememberSaveable { mutableIntStateOf(0) }
    var sets by remember { mutableStateOf(listOfNotNull(ClawdPack.set)) }
    LaunchedEffect(Unit) { sets = listOfNotNull(ClawdPack.set) + runCatching { repo.stickerSets() }.getOrDefault(emptyList()) }
    GlassBox(
        backdrop, Modifier.fillMaxWidth().height(320.dp), RoundedRectangle(28.dp),
        material = io.github.neoruaa.glasmio.glass.NavigationGlassMaterial.RegularLarge,
    ) { Column(Modifier.fillMaxSize()) {
        Box(Modifier.weight(1f)) {
            if (tab == 0) {
                LazyVerticalGrid(GridCells.Adaptive(44.dp), Modifier.fillMaxSize().padding(start = 6.dp, end = 6.dp, top = 8.dp)) {
                    items(EMOJI) { e ->
                        Box(Modifier.aspectRatio(1f).clip(RoundedCornerShape(10.dp)).clickable { onEmoji(e) }.themeTint(), contentAlignment = Alignment.Center) {
                            T(e, 28.sp)
                        }
                    }
                }
            } else StickerTab(repo, sets, onSticker)
        }
        // Glasmio's iOS segmented control (native selection lens).
        io.github.neoruaa.glasmio.ui.GlasmioSegmentedControl(
            items = listOf(0 to Strings.tr("Emoji"), 1 to Strings.tr("Stickers")),
            selected = tab,
            onSelected = { tab = it },
            modifier = Modifier.fillMaxWidth().padding(horizontal = 8.dp, vertical = 6.dp),
            backdrop = backdrop,
        )
    } }
}

@Composable
private fun StickerTab(repo: TelegramRepository, sets: List<StickerSet>, onSticker: (Sticker) -> Unit) {
    var query by rememberSaveable { mutableStateOf("") }
    val q = query.trim()
    // Search matches a sticker's emoji or its pack's title.
    val shown = if (q.isEmpty()) sets else sets.mapNotNull { set ->
        if (set.title.contains(q, ignoreCase = true)) set
        else set.copy(stickers = set.stickers.filter { it.emoji.contains(q) }).takeIf { it.stickers.isNotEmpty() }
    }
    val grid = rememberLazyGridState()
    val scope = rememberCoroutineScope()
    // Grid index of each pack's title row.
    val headers = remember(shown) { shown.runningFold(0) { at, set -> at + 1 + set.stickers.size }.dropLast(1) }
    val current by remember(headers) { derivedStateOf { headers.indexOfLast { it <= grid.firstVisibleItemIndex }.coerceAtLeast(0) } }
    Column(Modifier.fillMaxSize()) {
        LazyRow(Modifier.fillMaxWidth().padding(top = 8.dp), contentPadding = PaddingValues(horizontal = 10.dp), horizontalArrangement = Arrangement.spacedBy(6.dp)) {
            itemsIndexed(shown) { i, set ->
                val cover = set.stickers.firstOrNull() ?: return@itemsIndexed
                val path by produceState(cover.path, cover) { if (value == null) value = repo.stickerFile(cover) }
                Box(
                    Modifier.size(40.dp).clip(RoundedCornerShape(10.dp))
                        .background(if (i == current) Tg.Text.copy(alpha = 0.1f) else Color.Transparent)
                        .clickable { scope.launch { grid.animateScrollToItem(headers[i]) } }
                        .padding(4.dp),
                ) { StickerView(path, cover.kind, cover.emoji, 32.dp) }
            }
        }
        Row(
            Modifier.padding(horizontal = 10.dp, vertical = 8.dp).fillMaxWidth().height(36.dp)
                .background(Tg.Field, RoundedCornerShape(10.dp)).padding(horizontal = 10.dp),
            verticalAlignment = Alignment.CenterVertically,
        ) {
            Icon(Icons.Rounded.Search, Tg.Secondary, 18.dp)
            Spacer(Modifier.width(6.dp))
            Box(Modifier.weight(1f)) {
                if (query.isEmpty()) T("Search for stickers", 16.sp, Tg.Secondary)
                BasicTextField(
                    query, { query = it }, Modifier.fillMaxWidth(), singleLine = true,
                    textStyle = TextStyle(color = Tg.Text, fontSize = 16.sp, fontFamily = appFont()), cursorBrush = SolidColor(Tg.Accent),
                )
            }
        }
        LazyVerticalGrid(GridCells.Fixed(5), Modifier.fillMaxSize().padding(horizontal = 6.dp), state = grid) {
            shown.forEach { set ->
                item(span = { GridItemSpan(maxLineSpan) }) {
                    T(Strings.tr(set.title).uppercase(), 13.sp, Tg.Secondary, FontWeight.Medium, Modifier.padding(start = 8.dp, top = 8.dp, bottom = 4.dp))
                }
                items(set.stickers) { s ->
                    val path by produceState(s.path, s) { if (value == null) value = repo.stickerFile(s) }
                    Box(Modifier.aspectRatio(1f).clip(RoundedCornerShape(12.dp)).clickable { onSticker(s.copy(path = path)) }.padding(3.dp), contentAlignment = Alignment.Center) {
                        StickerView(path, s.kind, s.emoji, 64.dp)
                    }
                }
            }
        }
    }
}
