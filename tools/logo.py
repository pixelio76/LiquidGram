"""
LiquidGram logo: one soft white drop whose tip curls down-left like a chat bubble's tail (liquid + message in a
single shape) on a flat accent field. Minimal, in the spirit of single-shape app marks.
Generates the Android adaptive icon layers (background / foreground / monochrome for themed icons and icon packs),
the same layers as standalone SVGs, and a horizontal logo with the wordmark, all in branding/.
Canvas: 108x108 (adaptive icon), safe zone 21..87. Run: python tools/logo.py
"""
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
RES = ROOT / "app/src/main/res"
BRAND = ROOT / "branding"

# A teardrop pointing down-left along the diagonal: round body (centre 58,50, r 20), two concave flanks mirrored
# across the diagonal, and a softly rounded tip, so it reads as both a drop and a message bubble's tail.
# Tangent points sit where lines from the tip touch the circle (acos(r/d) = 60° either side of the diagonal),
# so the flanks join the body without a kink; each flank bows in slightly near the rounded tip.
DROP = ("M38.7,44.8 A20,20 0 1 1 63.2,69.3 "
        "C49.8,72.9 35.75,74.1 32.4,77.6 "
        "Q29.7,78.3 30.4,75.6 "
        "C33.9,72.25 35.1,58.2 38.7,44.8 Z")

BG = "#0A84FF"
TOP, BOTTOM = "#FFFFFF", "#D9ECFF"   # the drop: white at the top, a breath of blue at the tip


# ------------------------------------------------------------------ Android vector drawables

HEAD = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/logo.py -->\n'
VEC = ('<vector xmlns:android="http://schemas.android.com/apk/res/android" xmlns:aapt="http://schemas.android.com/aapt"\n'
       '    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">\n')


def android_layers():
    bg = HEAD + VEC + f'    <path android:pathData="M0,0 H108 V108 H0 Z" android:fillColor="{BG}"/>\n</vector>\n'
    fg = HEAD + VEC + (
        f'    <path android:pathData="{DROP}">\n'
        '        <aapt:attr name="android:fillColor">\n'
        '            <gradient android:type="linear" android:startX="68" android:startY="34" android:endX="32" android:endY="78">\n'
        f'                <item android:offset="0" android:color="#FF{TOP[1:]}"/>\n'
        f'                <item android:offset="1" android:color="#FF{BOTTOM[1:]}"/>\n'
        '            </gradient>\n'
        '        </aapt:attr>\n'
        '    </path>\n</vector>\n')
    mono = HEAD + VEC + f'    <path android:pathData="{DROP}" android:fillColor="#FF000000"/>\n</vector>\n'
    (RES / "drawable").mkdir(parents=True, exist_ok=True)
    (RES / "drawable/ic_launcher_background.xml").write_text(bg, encoding="utf-8")
    (RES / "drawable/ic_launcher_foreground.xml").write_text(fg, encoding="utf-8")
    (RES / "drawable/ic_launcher_monochrome.xml").write_text(mono, encoding="utf-8")
    adaptive = HEAD + ('<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
                       '    <background android:drawable="@drawable/ic_launcher_background"/>\n'
                       '    <foreground android:drawable="@drawable/ic_launcher_foreground"/>\n'
                       '    <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>\n'
                       '</adaptive-icon>\n')
    (RES / "mipmap-anydpi-v26").mkdir(parents=True, exist_ok=True)
    (RES / "mipmap-anydpi-v26/ic_launcher.xml").write_text(adaptive, encoding="utf-8")
    (RES / "mipmap-anydpi-v26/ic_launcher_round.xml").write_text(adaptive, encoding="utf-8")


# ------------------------------------------------------------------ SVG sources

GRAD = (f'<linearGradient id="drop" x1="68" y1="34" x2="32" y2="78" gradientUnits="userSpaceOnUse">'
        f'<stop offset="0" stop-color="{TOP}"/><stop offset="1" stop-color="{BOTTOM}"/></linearGradient>')


def svg(inner, w=1024, h=1024, view="0 0 108 108"):
    return f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="{view}">\n<defs>{GRAD}</defs>\n{inner}</svg>\n'


def svg_layers():
    BRAND.mkdir(exist_ok=True)
    for old in BRAND.glob("icon-*.svg"):
        old.unlink()
    background = f'<rect width="108" height="108" fill="{BG}"/>\n'
    foreground = f'<path d="{DROP}" fill="url(#drop)"/>\n'
    mono = f'<path d="{DROP}" fill="#000"/>\n'
    (BRAND / "icon-background.svg").write_text(svg(background), encoding="utf-8")
    (BRAND / "icon-foreground.svg").write_text(svg(foreground), encoding="utf-8")
    (BRAND / "icon-monochrome.svg").write_text(svg(mono), encoding="utf-8")
    (BRAND / "icon-full.svg").write_text(svg(background + foreground), encoding="utf-8")
    # Horizontal logo: the mark in a rounded square + wordmark (light and dark versions).
    for name, text in (("logo-light.svg", "#111111"), ("logo-dark.svg", "#FFFFFF")):
        inner = (f'<rect x="0" y="0" width="108" height="108" rx="28" fill="{BG}"/>\n'
                 f'<path d="{DROP}" fill="url(#drop)"/>\n'
                 f'<text x="132" y="70" font-family="SF Pro Display, Inter, Roboto, Helvetica, Arial, sans-serif" '
                 f'font-size="44" font-weight="700" letter-spacing="-1" fill="{text}">LiquidGram</text>\n')
        (BRAND / name).write_text(svg(inner, 1500, 324, "0 0 500 108"), encoding="utf-8")


if __name__ == "__main__":
    android_layers()
    svg_layers()
    print("ok")
